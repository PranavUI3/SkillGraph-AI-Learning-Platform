import uuid
from datetime import datetime
from typing import List, Optional
from fastapi import APIRouter, HTTPException, status, Depends
from app.database.connection import get_database
from app.core.security import get_current_user_id
from app.services.groq_service import groq_service
from app.models.roadmap import (
    RoadmapGenerateRequest, RoadmapProgressUpdate, RoadmapInDB,
    ModuleItem, TopicItem, PracticalExercise
)

router = APIRouter(prefix="/api/roadmap", tags=["Learning Roadmap"])

@router.post("/generate", response_model=RoadmapInDB)
def generate_roadmap_endpoint(payload: RoadmapGenerateRequest, user_id: str = Depends(get_current_user_id)):
    """Generate a full personalized learning roadmap with Groq AI."""
    db = get_database()
    roadmaps_col = db["roadmaps"]

    try:
        roadmap_data = groq_service.generate_roadmap(
            goal=payload.goal,
            current_skills=payload.current_skills,
            current_proficiency=payload.current_proficiency,
            available_hours_per_week=payload.available_hours_per_week,
            preferred_duration_weeks=payload.preferred_duration_weeks or 8
        )
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to generate roadmap with Groq AI: {str(e)}"
        )

    roadmap_id = str(uuid.uuid4())
    now = datetime.utcnow()

    modules_raw = roadmap_data.get("modules", [])
    total_topics = 0

    # Ensure unique IDs for all topics and modules
    cleaned_modules = []
    for mod_idx, mod in enumerate(modules_raw, 1):
        mod_id = mod.get("id") or f"mod_{mod_idx}"
        cleaned_topics = []
        for top_idx, top in enumerate(mod.get("topics", []), 1):
            top_id = top.get("id") or f"top_{mod_idx}_{top_idx}"
            total_topics += 1
            exercises = []
            for ex in top.get("practical_exercises", []):
                exercises.append({
                    "title": ex.get("title", "Hands-on Exercise"),
                    "description": ex.get("description", "Apply learned concepts."),
                    "deliverable": ex.get("deliverable", "Working code repository")
                })

            cleaned_topics.append({
                "id": str(top_id),
                "title": top.get("title", f"Topic {top_idx}"),
                "description": top.get("description", ""),
                "estimated_hours": float(top.get("estimated_hours", 2.0)),
                "difficulty": top.get("difficulty", payload.current_proficiency),
                "prerequisites": top.get("prerequisites", []),
                "learning_objectives": top.get("learning_objectives", []),
                "practical_exercises": exercises,
                "completed": False,
                "completed_at": None
            })

        cleaned_modules.append({
            "id": str(mod_id),
            "title": mod.get("title", f"Module {mod_idx}"),
            "description": mod.get("description", ""),
            "week_number": mod.get("week_number", mod_idx),
            "estimated_duration": mod.get("estimated_duration", "1-2 Weeks"),
            "topics": cleaned_topics
        })

    doc = {
        "id": roadmap_id,
        "user_id": user_id,
        "goal": payload.goal,
        "current_proficiency": payload.current_proficiency,
        "available_hours_per_week": payload.available_hours_per_week,
        "total_weeks": int(roadmap_data.get("total_weeks", payload.preferred_duration_weeks or 8)),
        "modules": cleaned_modules,
        "progress_percentage": 0.0,
        "total_topics": total_topics,
        "completed_topics": 0,
        "created_at": now,
        "updated_at": now
    }

    roadmaps_col.insert_one(doc)

    return RoadmapInDB(**doc)

@router.get("", response_model=Optional[RoadmapInDB])
def get_current_roadmap(user_id: str = Depends(get_current_user_id)):
    """Fetch the latest active roadmap for current student."""
    db = get_database()
    doc = db["roadmaps"].find_one({"user_id": user_id}, sort=[("updated_at", -1)])
    if not doc:
        return None
    return RoadmapInDB(**doc)

@router.get("/all", response_model=List[RoadmapInDB])
def get_all_user_roadmaps(user_id: str = Depends(get_current_user_id)):
    """Fetch all roadmaps generated by student."""
    db = get_database()
    cursor = db["roadmaps"].find({"user_id": user_id}).sort("updated_at", -1)
    return [RoadmapInDB(**doc) for doc in cursor]

@router.get("/{roadmap_id}", response_model=RoadmapInDB)
def get_roadmap_by_id(roadmap_id: str, user_id: str = Depends(get_current_user_id)):
    """Fetch a specific roadmap by ID."""
    db = get_database()
    doc = db["roadmaps"].find_one({"id": roadmap_id, "user_id": user_id})
    if not doc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Roadmap not found.")
    return RoadmapInDB(**doc)

@router.patch("/{roadmap_id}/progress")
def update_topic_progress(
    roadmap_id: str,
    payload: RoadmapProgressUpdate,
    user_id: str = Depends(get_current_user_id)
):
    """Mark a topic completed or uncompleted and update total progress percentage."""
    db = get_database()
    roadmaps_col = db["roadmaps"]

    doc = roadmaps_col.find_one({"id": roadmap_id, "user_id": user_id})
    if not doc:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Roadmap not found.")

    modules = doc.get("modules", [])
    topic_found = False
    completed_topics_count = 0
    total_topics_count = 0
    now = datetime.utcnow()

    for m in modules:
        for t in m.get("topics", []):
            total_topics_count += 1
            if str(t.get("id")) == str(payload.topic_id):
                t["completed"] = payload.completed
                t["completed_at"] = now if payload.completed else None
                topic_found = True
            if t.get("completed"):
                completed_topics_count += 1

    if not topic_found:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Topic ID not found in roadmap.")

    progress_pct = round((completed_topics_count / total_topics_count * 100) if total_topics_count > 0 else 0, 1)

    roadmaps_col.update_one(
        {"id": roadmap_id},
        {
            "$set": {
                "modules": modules,
                "completed_topics": completed_topics_count,
                "total_topics": total_topics_count,
                "progress_percentage": progress_pct,
                "updated_at": now
            }
        }
    )

    return {
        "success": True,
        "topic_id": payload.topic_id,
        "completed": payload.completed,
        "progress_percentage": progress_pct,
        "completed_topics": completed_topics_count,
        "total_topics": total_topics_count
    }
