import React, { useState, useEffect } from 'react';
import api from '../services/api';
import { 
  Map, 
  Sparkles, 
  CheckCircle2, 
  Circle, 
  Clock, 
  BookOpen, 
  Code2, 
  ChevronDown, 
  ChevronUp, 
  AlertCircle, 
  Check, 
  ListFilter,
  Plus
} from 'lucide-react';

const RoadmapPage = () => {
  const [roadmap, setRoadmap] = useState(null);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [showGenerateModal, setShowGenerateModal] = useState(false);
  const [expandedTopics, setExpandedTopics] = useState({});
  const [error, setError] = useState('');

  // Generator form inputs
  const [formData, setFormData] = useState({
    goal: 'Full Stack React & FastAPI Developer',
    current_skills: 'HTML, CSS, Basic JavaScript, Python fundamentals',
    current_proficiency: 'Beginner',
    available_hours_per_week: 12,
    preferred_duration_weeks: 8
  });

  useEffect(() => {
    fetchActiveRoadmap();
  }, []);

  const fetchActiveRoadmap = async () => {
    try {
      setLoading(true);
      const res = await api.get('/roadmap');
      setRoadmap(res.data);
    } catch (err) {
      console.error(err);
      setError('Could not fetch active roadmap.');
    } finally {
      setLoading(false);
    }
  };

  const handleGenerate = async (e) => {
    e.preventDefault();
    setGenerating(true);
    setError('');

    try {
      const skillsArray = formData.current_skills
        .split(',')
        .map(s => s.trim())
        .filter(Boolean);

      const res = await api.post('/roadmap/generate', {
        goal: formData.goal,
        current_skills: skillsArray,
        current_proficiency: formData.current_proficiency,
        available_hours_per_week: Number(formData.available_hours_per_week),
        preferred_duration_weeks: Number(formData.preferred_duration_weeks)
      });

      setRoadmap(res.data);
      setShowGenerateModal(false);
    } catch (err) {
      console.error(err);
      setError(err.response?.data?.detail || 'Failed to generate roadmap with Groq AI.');
    } finally {
      setGenerating(false);
    }
  };

  const toggleTopicProgress = async (topicId, currentStatus) => {
    if (!roadmap) return;
    try {
      const res = await api.patch(`/roadmap/${roadmap.id}/progress`, {
        topic_id: topicId,
        completed: !currentStatus
      });

      // Update local state smoothly
      const updatedModules = roadmap.modules.map(mod => ({
        ...mod,
        topics: mod.topics.map(top => {
          if (top.id === topicId) {
            return { ...top, completed: !currentStatus };
          }
          return top;
        })
      }));

      setRoadmap({
        ...roadmap,
        modules: updatedModules,
        progress_percentage: res.data.progress_percentage,
        completed_topics: res.data.completed_topics
      });
    } catch (err) {
      console.error('Failed to update topic progress:', err);
    }
  };

  const toggleTopicExpand = (topicId) => {
    setExpandedTopics(prev => ({ ...prev, [topicId]: !prev[topicId] }));
  };

  if (loading) {
    return (
      <div className="flex flex-col items-center justify-center min-h-[60vh] gap-3">
        <div className="w-10 h-10 border-4 border-indigo-500/30 border-t-indigo-500 rounded-full animate-spin" />
        <p className="text-sm text-slate-400">Loading learning roadmap...</p>
      </div>
    );
  }

  return (
    <div className="space-y-6 max-w-5xl mx-auto">
      {/* Top Banner & Actions */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-800 pb-5">
        <div>
          <h1 className="text-2xl font-bold text-white tracking-tight flex items-center gap-2.5">
            <Map className="w-6 h-6 text-indigo-400" />
            <span>AI-Powered Learning Roadmap</span>
          </h1>
          <p className="text-sm text-slate-400 mt-1">
            Modular, milestone-driven technical path generated by Groq and saved to your profile.
          </p>
        </div>

        <button
          onClick={() => setShowGenerateModal(true)}
          className="px-4 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold shadow-md shadow-indigo-600/30 transition-all flex items-center gap-2 shrink-0 self-start sm:self-auto"
        >
          <Sparkles className="w-4 h-4" />
          <span>Generate New Roadmap</span>
        </button>
      </div>

      {error && (
        <div className="p-4 rounded-xl bg-rose-500/10 border border-rose-500/20 text-rose-400 text-sm flex items-center gap-2.5">
          <AlertCircle className="w-5 h-5 shrink-0" />
          <span>{error}</span>
        </div>
      )}

      {roadmap ? (
        <div className="space-y-6">
          {/* Roadmap Header Summary Card */}
          <div className="rounded-2xl bg-gradient-to-r from-indigo-950/60 via-purple-950/40 to-slate-900 border border-indigo-500/30 p-6 sm:p-8 backdrop-blur-sm shadow-xl">
            <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-6">
              <div>
                <span className="text-xs font-bold uppercase tracking-wider text-indigo-400">
                  Target Engineering Goal
                </span>
                <h2 className="text-xl sm:text-2xl font-extrabold text-white mt-1">
                  {roadmap.goal}
                </h2>
                <div className="mt-3 flex flex-wrap items-center gap-3 text-xs text-slate-300">
                  <span className="px-2.5 py-1 rounded-md bg-slate-800/80 border border-slate-700/80">
                    Duration: {roadmap.total_weeks} Weeks
                  </span>
                  <span className="px-2.5 py-1 rounded-md bg-slate-800/80 border border-slate-700/80">
                    Hours: {roadmap.available_hours_per_week} hrs/week
                  </span>
                  <span className="px-2.5 py-1 rounded-md bg-indigo-500/10 text-indigo-300 border border-indigo-500/20">
                    Level: {roadmap.current_proficiency}
                  </span>
                </div>
              </div>

              {/* Progress visual */}
              <div className="shrink-0 lg:w-64 p-4 rounded-xl bg-slate-900/80 border border-slate-800">
                <div className="flex items-center justify-between text-xs mb-2">
                  <span className="text-slate-400">Completion</span>
                  <span className="font-bold text-indigo-400 text-sm">{roadmap.progress_percentage}%</span>
                </div>
                <div className="w-full bg-slate-800 h-2.5 rounded-full overflow-hidden">
                  <div
                    className="bg-gradient-to-r from-indigo-500 to-purple-500 h-full rounded-full transition-all duration-500"
                    style={{ width: `${roadmap.progress_percentage}%` }}
                  />
                </div>
                <p className="text-[11px] text-slate-400 mt-2 text-center">
                  {roadmap.completed_topics} of {roadmap.total_topics} topics completed
                </p>
              </div>
            </div>
          </div>

          {/* Modules List */}
          <div className="space-y-6">
            {roadmap.modules.map((mod, modIdx) => (
              <div
                key={mod.id || modIdx}
                className="rounded-2xl bg-slate-900/80 border border-slate-800 p-6 backdrop-blur-sm"
              >
                {/* Module title bar */}
                <div className="flex flex-col sm:flex-row sm:items-center justify-between pb-4 border-b border-slate-800/80 gap-2 mb-4">
                  <div>
                    <span className="text-xs font-bold uppercase tracking-wider text-indigo-400">
                      Module {mod.week_number || modIdx + 1} • {mod.estimated_duration}
                    </span>
                    <h3 className="text-base sm:text-lg font-bold text-white mt-0.5">
                      {mod.title}
                    </h3>
                    {mod.description && (
                      <p className="text-xs text-slate-400 mt-1 max-w-2xl">{mod.description}</p>
                    )}
                  </div>
                </div>

                {/* Topics in this module */}
                <div className="space-y-3">
                  {mod.topics.map((topic, topIdx) => {
                    const isExpanded = expandedTopics[topic.id];
                    return (
                      <div
                        key={topic.id || topIdx}
                        className={`rounded-xl border transition-all ${
                          topic.completed
                            ? 'bg-emerald-950/10 border-emerald-500/25'
                            : 'bg-slate-800/30 border-slate-700/50 hover:border-slate-600'
                        }`}
                      >
                        {/* Topic Row */}
                        <div className="p-4 flex items-center justify-between gap-4">
                          <div className="flex items-start gap-3 min-w-0">
                            <button
                              type="button"
                              onClick={() => toggleTopicProgress(topic.id, topic.completed)}
                              className={`mt-0.5 shrink-0 transition-colors ${
                                topic.completed ? 'text-emerald-400' : 'text-slate-500 hover:text-slate-300'
                              }`}
                            >
                              {topic.completed ? (
                                <CheckCircle2 className="w-5 h-5 fill-emerald-500/20" />
                              ) : (
                                <Circle className="w-5 h-5" />
                              )}
                            </button>

                            <div className="min-w-0">
                              <h4 className={`text-sm font-semibold truncate ${
                                topic.completed ? 'line-through text-slate-400' : 'text-white'
                              }`}>
                                {topic.title}
                              </h4>
                              <p className="text-xs text-slate-400 mt-0.5 line-clamp-1">
                                {topic.description}
                              </p>
                            </div>
                          </div>

                          <div className="flex items-center gap-3 shrink-0">
                            <span className="hidden sm:inline-flex items-center gap-1 text-[11px] text-slate-400">
                              <Clock className="w-3.5 h-3.5" />
                              {topic.estimated_hours}h
                            </span>

                            <button
                              type="button"
                              onClick={() => toggleTopicExpand(topic.id)}
                              className="p-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs flex items-center gap-1"
                            >
                              <span>Details</span>
                              {isExpanded ? <ChevronUp className="w-3.5 h-3.5" /> : <ChevronDown className="w-3.5 h-3.5" />}
                            </button>
                          </div>
                        </div>

                        {/* Expandable Topic Details */}
                        {isExpanded && (
                          <div className="px-5 pb-5 pt-2 border-t border-slate-800/80 space-y-4 text-xs">
                            {/* Learning Objectives */}
                            {topic.learning_objectives && topic.learning_objectives.length > 0 && (
                              <div>
                                <h5 className="font-semibold text-indigo-300 flex items-center gap-1.5 mb-1.5">
                                  <BookOpen className="w-3.5 h-3.5" />
                                  Learning Objectives
                                </h5>
                                <ul className="list-disc list-inside text-slate-300 space-y-1 pl-1">
                                  {topic.learning_objectives.map((obj, i) => (
                                    <li key={i}>{obj}</li>
                                  ))}
                                </ul>
                              </div>
                            )}

                            {/* Practical Exercises */}
                            {topic.practical_exercises && topic.practical_exercises.length > 0 && (
                              <div>
                                <h5 className="font-semibold text-emerald-300 flex items-center gap-1.5 mb-1.5">
                                  <Code2 className="w-3.5 h-3.5" />
                                  Hands-on Practical Exercise
                                </h5>
                                <div className="space-y-2">
                                  {topic.practical_exercises.map((ex, i) => (
                                    <div key={i} className="p-3 rounded-lg bg-[#060a13] border border-slate-800">
                                      <p className="font-semibold text-white">{ex.title}</p>
                                      <p className="text-slate-400 mt-1">{ex.description}</p>
                                      {ex.deliverable && (
                                        <p className="mt-1 text-indigo-400 font-mono text-[11px]">
                                          Deliverable: {ex.deliverable}
                                        </p>
                                      )}
                                    </div>
                                  ))}
                                </div>
                              </div>
                            )}

                            {/* Prerequisites */}
                            {topic.prerequisites && topic.prerequisites.length > 0 && (
                              <div className="flex items-center gap-2 text-slate-400">
                                <span className="font-semibold">Prerequisites:</span>
                                <span>{topic.prerequisites.join(', ')}</span>
                              </div>
                            )}
                          </div>
                        )}
                      </div>
                    );
                  })}
                </div>
              </div>
            ))}
          </div>
        </div>
      ) : (
        /* Empty State */
        <div className="text-center py-20 rounded-2xl bg-slate-900/60 border border-dashed border-slate-800 p-8">
          <Map className="w-12 h-12 text-slate-600 mx-auto mb-3" />
          <h3 className="text-lg font-bold text-white">No active roadmap found</h3>
          <p className="text-xs text-slate-400 max-w-sm mx-auto mt-1 mb-5">
            Click below to generate a tailored step-by-step engineering curriculum based on your career goals.
          </p>
          <button
            onClick={() => setShowGenerateModal(true)}
            className="px-5 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold shadow-md shadow-indigo-600/30 transition-all flex items-center gap-2 mx-auto"
          >
            <Sparkles className="w-4 h-4" />
            <span>Generate Custom Roadmap</span>
          </button>
        </div>
      )}

      {/* GENERATE ROADMAP MODAL */}
      {showGenerateModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm animate-in fade-in duration-150">
          <div className="w-full max-w-lg rounded-2xl bg-slate-900 border border-slate-800 p-6 sm:p-8 shadow-2xl relative">
            <h3 className="text-lg font-bold text-white flex items-center gap-2 mb-1">
              <Sparkles className="w-5 h-5 text-indigo-400" />
              <span>Configure AI Roadmap</span>
            </h3>
            <p className="text-xs text-slate-400 mb-5">
              Groq AI will formulate an optimized syllabus based on your current knowledge and time limits.
            </p>

            <form onSubmit={handleGenerate} className="space-y-4 text-xs">
              <div>
                <label className="block font-semibold text-slate-300 uppercase tracking-wider mb-1.5">
                  Target Learning Goal / Career Target
                </label>
                <input
                  type="text"
                  required
                  value={formData.goal}
                  onChange={(e) => setFormData({ ...formData, goal: e.target.value })}
                  placeholder="e.g. Full Stack React & FastAPI Developer"
                  className="w-full px-3.5 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-white text-sm focus:outline-none focus:ring-2 focus:ring-indigo-500"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-300 uppercase tracking-wider mb-1.5">
                  Current Skills You Already Know (Comma-separated)
                </label>
                <input
                  type="text"
                  value={formData.current_skills}
                  onChange={(e) => setFormData({ ...formData, current_skills: e.target.value })}
                  placeholder="e.g. HTML, CSS, JavaScript, Basic Python"
                  className="w-full px-3.5 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-white text-sm focus:outline-none focus:ring-2 focus:ring-indigo-500"
                />
              </div>

              <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
                <div>
                  <label className="block font-semibold text-slate-300 uppercase tracking-wider mb-1.5">
                    Proficiency
                  </label>
                  <select
                    value={formData.current_proficiency}
                    onChange={(e) => setFormData({ ...formData, current_proficiency: e.target.value })}
                    className="w-full px-3 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-white text-xs focus:outline-none focus:ring-2 focus:ring-indigo-500"
                  >
                    <option value="Beginner">Beginner</option>
                    <option value="Intermediate">Intermediate</option>
                    <option value="Advanced">Advanced</option>
                  </select>
                </div>

                <div>
                  <label className="block font-semibold text-slate-300 uppercase tracking-wider mb-1.5">
                    Hours / Week
                  </label>
                  <input
                    type="number"
                    min="2"
                    max="60"
                    value={formData.available_hours_per_week}
                    onChange={(e) => setFormData({ ...formData, available_hours_per_week: e.target.value })}
                    className="w-full px-3 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-white text-xs focus:outline-none focus:ring-2 focus:ring-indigo-500"
                  />
                </div>

                <div>
                  <label className="block font-semibold text-slate-300 uppercase tracking-wider mb-1.5">
                    Target Weeks
                  </label>
                  <input
                    type="number"
                    min="2"
                    max="24"
                    value={formData.preferred_duration_weeks}
                    onChange={(e) => setFormData({ ...formData, preferred_duration_weeks: e.target.value })}
                    className="w-full px-3 py-2.5 rounded-xl bg-slate-800/80 border border-slate-700 text-white text-xs focus:outline-none focus:ring-2 focus:ring-indigo-500"
                  />
                </div>
              </div>

              <div className="mt-6 pt-4 border-t border-slate-800 flex items-center justify-end gap-3">
                <button
                  type="button"
                  disabled={generating}
                  onClick={() => setShowGenerateModal(false)}
                  className="px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-semibold"
                >
                  Cancel
                </button>

                <button
                  type="submit"
                  disabled={generating}
                  className="px-5 py-2.5 rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-semibold shadow-md shadow-indigo-600/30 flex items-center gap-2"
                >
                  {generating ? (
                    <>
                      <div className="w-4 h-4 border-2 border-white/30 border-t-white rounded-full animate-spin" />
                      <span>Generating with Groq...</span>
                    </>
                  ) : (
                    <>
                      <Sparkles className="w-4 h-4" />
                      <span>Build Roadmap</span>
                    </>
                  )}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};

export default RoadmapPage;
